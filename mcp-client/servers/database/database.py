# Default limit for SELECT queries to prevent large result sets
DEFAULT_LIMIT = 1000

# Initialize FastMCP server
mcp = FastMCP("database")

# Primary adapter: user-connected PostgreSQL or explicitly-connected SQLite.
# Never overridden by system-level session file connections.
_primary_adapter: Optional[DatabaseAdapter] = None

# Session adapter: system-managed SQLite for uploaded session files.
# Set by connect_session_sqlite; does NOT override _primary_adapter.
_session_adapter: Optional[DatabaseAdapter] = None

# When set, list_tables (and schema discovery) will only surface these table names
# from the session adapter. Populated from the UI data-source selector so only
# the user's chosen files' tables are visible (not every table in the shared SQLite).
_session_allowed_tables: Optional[set] = None

# Store the latest reviewed CREATE TABLE proposal.
# create_table() will only execute when it matches this reviewed proposal
# and user_confirmed=True is explicitly provided.
_pending_create_table_review: Optional[dict[str, Any]] = None


def get_adapter() -> DatabaseAdapter:
    """Return primary adapter if available, else session adapter."""
    if _primary_adapter is not None:
        return _primary_adapter
    if _session_adapter is not None:
        return _session_adapter
    raise RuntimeError(
        "Database not connected. Please use 'connect_db' (PostgreSQL) or "
        "'connect_sqlite' (SQLite) tool first."
    )


async def _adapter_for_table(table_name: str) -> DatabaseAdapter:
    """Return the adapter that owns *table_name*.

    Heuristic: session-file tables are always named ``t_<...>`` (generated by
    the file ingestion service).  Everything else belongs to the primary DB.
    When only one adapter is connected, that adapter is always returned.
    """
    if _primary_adapter is not None and _session_adapter is not None:
        # Session tables are always prefixed with t_ by the file ingestion service.
        if str(table_name).startswith("t_"):
            return _session_adapter
        return _primary_adapter
    if _primary_adapter is not None:
        return _primary_adapter
    if _session_adapter is not None:
        return _session_adapter
    raise RuntimeError(
        "Database not connected. Please use 'connect_db' (PostgreSQL) or "
        "'connect_sqlite' (SQLite) tool first."
    )


def _split_column_defs(columns: str) -> list[str]:
    """Split SQL column definitions by top-level commas.

    Example: "a VARCHAR(10), b DECIMAL(10,2), c TEXT" ->
    ["a VARCHAR(10)", "b DECIMAL(10,2)", "c TEXT"]
    """
    items: list[str] = []
    current: list[str] = []
    depth = 0

    for ch in columns:
        if ch == "(":
            depth += 1
        elif ch == ")" and depth > 0:
            depth -= 1

        if ch == "," and depth == 0:
            part = "".join(current).strip()
            if part:
                items.append(part)
            current = []
            continue

        current.append(ch)

    last = "".join(current).strip()
    if last:
        items.append(last)

    return items


def _to_variable_type_rows(columns: str) -> list[tuple[str, str]]:
    """Parse column definition string into (variable, type) rows.

    The type may span multiple whitespace-separated tokens when an LLM emits
    something like ``DECIMAL(10, 2)`` (space after the inner comma). We walk
    forward from the second token, consuming tokens until paren depth returns
    to zero — that's where the type ends and constraints (NOT NULL, …) begin.
    Constraints are dropped from the displayed type so the review widget sees
    only the storage type the user needs to validate.
    """
    rows: list[tuple[str, str]] = []
    constraints = {"primary", "foreign", "unique", "check", "constraint"}

    for part in _split_column_defs(columns):
        tokens = part.split()
        if len(tokens) < 2:
            continue

        first = tokens[0].strip('"`').lower()
        if first in constraints:
            continue

        variable = tokens[0].strip('"`')

        type_tokens: list[str] = []
        depth = 0
        for tok in tokens[1:]:
            type_tokens.append(tok)
            depth += tok.count("(") - tok.count(")")
            if depth == 0:
                break
        if not type_tokens:
            continue
        dtype = " ".join(type_tokens)
        rows.append((variable, dtype))

    return rows



