def _add_limit(query: str) -> str:
    """Auto-add LIMIT to SELECT queries if not present."""
    query = query.strip()
    # Normalize trailing semicolon so appending LIMIT stays valid SQL.
    base_query = query[:-1].strip() if query.endswith(";") else query
    query_upper = base_query.upper()

    # Only add limit to SELECT queries
    if not query_upper.startswith("SELECT"):
        return query

    # Skip if already has LIMIT
    if "LIMIT" in query_upper:
        return query

    # Add LIMIT
    return f"{base_query} LIMIT {DEFAULT_LIMIT}"


def _first_table_name_from_sql(query: str) -> Optional[str]:
    """Best-effort extraction of the first table name referenced in a SQL query.

    Handles the most common patterns:
      SELECT ... FROM <table>
      INSERT INTO <table>
      UPDATE <table>
      DELETE FROM <table>
    Returns None if no match is found.
    """
    patterns = (
        r"\bFROM\s+([`\"\[]?[\w.]+[`\"\]]?)",
        r"\bJOIN\s+([`\"\[]?[\w.]+[`\"\]]?)",
        r"\bINTO\s+([`\"\[]?[\w.]+[`\"\]]?)",
        r"\bUPDATE\s+([`\"\[]?[\w.]+[`\"\]]?)",
    )
    upper = query.upper()
    for pattern in patterns:
        m = re.search(pattern, upper)
        if m:
            # Return the original-case token from the same position.
            start = m.start(1)
            end = m.end(1)
            raw = query[start:end].strip("`\"[]")
            # Strip schema prefix (e.g. "public.users" → "users")
            return raw.split(".")[-1]
    return None


@mcp.tool()
async def execute_query(query: str) -> str:
    """Execute a custom SQL query.

    Automatically routes to the correct database (primary or session file)
    based on the first table name referenced in the query.

    Args:
        query: SQL query to execute
    """
    query = _add_limit(query)

    # When both adapters exist, route based on the first table in the SQL.
    if _primary_adapter is not None and _session_adapter is not None:
        table_name = _first_table_name_from_sql(query)
        adapter = await _adapter_for_table(table_name or "")
    else:
        adapter = get_adapter()

    return await adapter.execute_query(query)


@mcp.tool()
async def export_table_to_excel(
    table_name: str,
    columns: str = "*",
    where_clause: str | None = None,
    limit: int | None = None,
    offset: int | None = None,
) -> dict:
    """Export table data to Excel file. Returns dict with base64 content and filename.

    Streams rows from the DB in chunks via ``adapter.stream_query`` and writes
    them through xlsxwriter's ``constant_memory`` mode to a temp .xlsx on
    disk — each row is flushed as the next one is written, so the full
    result set is never materialized in RAM.

    Args:
        table_name: Name of the table to export
        columns: Column names to export (default: "*")
        where_clause: Optional WHERE clause to filter data (without the WHERE keyword)
        limit: Optional SQLite LIMIT (row cap)
        offset: Optional SQLite OFFSET (skip rows; use with limit for slices e.g. rows 10–20 → limit 11, offset 9)
    """
    import base64
    import logging
    import os
    import tempfile
    from datetime import date, datetime
    from decimal import Decimal
    from uuid import UUID

    logging.basicConfig(level=logging.INFO)
    logger = logging.getLogger(__name__)

    try:
        import xlsxwriter
    except ImportError:
        return {
            "error": (
                "xlsxwriter is required for Excel export. From repo root: "
                "`cd database && uv sync`, then restart the API server."
            )
        }

    def _xlsx_safe(v):
        # xlsxwriter accepts None/bool/int/float/str/datetime/date natively.
        # Coerce other DB types so write_row doesn't fall back to slow conversion.
        if v is None or isinstance(v, (bool, int, float, str, datetime, date)):
            return v
        if isinstance(v, Decimal):
            return float(v)
        if isinstance(v, UUID):
            return str(v)
        if isinstance(v, (bytes, bytearray)):
            return v.hex()
        return str(v)

    # Build query
    query = f"SELECT {columns} FROM {table_name}"
    if where_clause:
        query += f" WHERE {where_clause}"
    if limit is not None:
        lim = int(limit)
        if lim < 0:
            return {"error": "limit must be non-negative"}
        query += f" LIMIT {lim}"
    elif offset is not None:
        # SQLite requires LIMIT when using OFFSET; -1 means no upper bound.
        query += " LIMIT -1"
    if offset is not None:
        off = int(offset)
        if off < 0:
            return {"error": "offset must be non-negative"}
        query += f" OFFSET {off}"

    logger.info(f"[export_table_to_excel] table={table_name}, query={query}")

    adapter = await _adapter_for_table(table_name)

    tmp = tempfile.NamedTemporaryFile(suffix=".xlsx", delete=False)
    tmp_path = tmp.name
    tmp.close()

    try:
        # constant_memory=True: each row is flushed as the next is written; can't
        #   seek back to modify earlier cells.
        # strings_to_urls=False: skip the regex that turns "http://..." strings
        #   into hyperlinks — significantly faster on text-heavy exports.
        wb = xlsxwriter.Workbook(
            tmp_path,
            {
                "constant_memory": True,
                "strings_to_urls": False,
                "default_date_format": "yyyy-mm-dd hh:mm:ss",
            },
        )
        col_names: list[str] | None = None
        row_count = 0
        try:
            ws = wb.add_worksheet()
            row_idx = 0
            try:
                async for cols, rows in adapter.stream_query(query, chunk_size=5000):
                    if col_names is None:
                        col_names = list(cols)
                        ws.write_row(0, 0, col_names)
                        row_idx = 1
                    for row in rows:
                        ws.write_row(row_idx, 0, [_xlsx_safe(row[c]) for c in col_names])
                        row_idx += 1
                    row_count += len(rows)
            except Exception as e:
                logger.error(f"[export_table_to_excel] query stream error: {e}")
                return {"error": str(e)}
        finally:
            wb.close()

        if col_names is None:
            return {"error": "No data found"}

        file_size = os.path.getsize(tmp_path)

        # Stream the xlsx file through base64 so we don't hold both the raw
        # bytes and the encoded string in RAM at once. Reads in multiples of 3
        # so each chunk encodes without intermediate padding.
        b64_buf = bytearray()
        with open(tmp_path, "rb") as f:
            while True:
                chunk = f.read(3 * 64 * 1024)
                if not chunk:
                    break
                b64_buf += base64.b64encode(chunk)
        b64 = b64_buf.decode("ascii")
        del b64_buf

        filename = f"{table_name}.xlsx"
        logger.info(
            f"[export_table_to_excel] success: {row_count} rows, "
            f"file={file_size} bytes, base64 length: {len(b64)}"
        )
        return {"base64": b64, "filename": filename, "row_count": row_count}
    except Exception as e:
        logger.exception("[export_table_to_excel] ERROR")
        return {"error": str(e)}
    finally:
        try:
            os.unlink(tmp_path)
        except OSError:
            pass


