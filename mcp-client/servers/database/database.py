@mcp.tool()
async def connect_db(
    host: str,
    port: int,
    database: str,
    username: str,
    password: str
) -> str:
    """Connect to a PostgreSQL database. You must call this first before using any other database operations.

    Args:
        host: Database host (e.g., "localhost" or "127.0.0.1")
        port: Database port (default PostgreSQL port is 5432)
        database: Database name
        username: Database username
        password: Database password
    """
    global _primary_adapter

    if _primary_adapter is not None:
        await _primary_adapter.disconnect()

    _primary_adapter = DatabaseAdapterFactory.create_postgres()
    result = await _primary_adapter.connect(
        host=host,
        port=port,
        database=database,
        username=username,
        password=password
    )

    if "Failed" in result or "Error" in result:
        _primary_adapter = None

    return result


@mcp.tool()
async def connect_sqlite(file_path: str) -> str:
    """Connect to a SQLite database file (user-initiated). Creates the file if it doesn't exist.

    This sets the *primary* adapter and replaces any existing primary connection.
    Use ``connect_session_sqlite`` for system-managed session-file connections.

    Args:
        file_path: Path to the SQLite database file (e.g., "/path/to/db.sqlite" or "sqlite:///path/to/db.sqlite")
    """
    global _primary_adapter

    if _primary_adapter is not None:
        await _primary_adapter.disconnect()

    _primary_adapter = DatabaseAdapterFactory.create_sqlite()
    result = await _primary_adapter.connect(file_path=file_path)

    if "Failed" in result or "Error" in result:
        _primary_adapter = None

    return result


@mcp.tool()
async def connect_session_sqlite(file_path: str, allowed_tables: Optional[str] = None) -> str:
    """Connect a session-scoped SQLite file (uploaded by the user) WITHOUT overriding the primary DB.

    This sets only the *session* adapter so that the user's PostgreSQL connection
    (or any explicit primary connection) remains intact and can be queried alongside
    the session file.

    Args:
        file_path: Path to the SQLite database file for the uploaded session file.
        allowed_tables: Optional comma-separated list of table names to expose from this
            SQLite file. When set, ``list_tables`` will only surface these tables so the
            LLM sees exactly the tables from the files the user selected — not every table
            in the shared session SQLite (which may contain tables from other uploaded files).
    """
    global _session_adapter, _session_allowed_tables

    if _session_adapter is not None:
        await _session_adapter.disconnect()

    _session_adapter = DatabaseAdapterFactory.create_sqlite()
    result = await _session_adapter.connect(file_path=file_path)

    if "Failed" in result or "Error" in result:
        _session_adapter = None
        _session_allowed_tables = None
    else:
        if allowed_tables:
            _session_allowed_tables = {t.strip() for t in allowed_tables.split(",") if t.strip()}
        else:
            _session_allowed_tables = None

    return result


@mcp.tool()
async def disconnect_session_sqlite() -> str:
    """Disconnect the session-scoped SQLite adapter and clear the allowed-tables filter.

    Call this when the user switches away from a file (e.g. switches back to DB-only mode)
    so that subsequent ``list_tables`` / queries no longer surface tables from the old
    session file.
    """
    global _session_adapter, _session_allowed_tables

    if _session_adapter is None:
        _session_allowed_tables = None
        return "No session file adapter connected."

    try:
        await _session_adapter.disconnect()
    except Exception:
        pass
    finally:
        _session_adapter = None
        _session_allowed_tables = None

    return "Session file adapter disconnected."


@mcp.tool()
async def get_connection_info() -> str:
    """Get current database connection information (without showing password)."""
    parts: list[str] = []
    if _primary_adapter is not None:
        parts.append("Primary DB: " + await _primary_adapter.get_connection_info())
    if _session_adapter is not None:
        parts.append("Session file DB: " + await _session_adapter.get_connection_info())
    if not parts:
        return "Not connected to any database. Please use 'connect_db' or 'connect_sqlite' tool first."
    return "\n".join(parts)


@mcp.tool()
async def disconnect_database() -> str:
    """Disconnect from all active database connections (primary and session)."""
    global _primary_adapter, _session_adapter, _session_allowed_tables
    messages: list[str] = []
    if _primary_adapter is not None:
        messages.append(await _primary_adapter.disconnect())
        _primary_adapter = None
    if _session_adapter is not None:
        messages.append(await _session_adapter.disconnect())
        _session_adapter = None
    _session_allowed_tables = None
    return "\n".join(messages) if messages else "No active database connection."


