def _filter_tables_result(tables_result: str, allowed: set) -> str:
    """Filter a 'Tables in database: a, b, c' string to only the names in *allowed*."""
    prefix = "Tables in database:"
    if prefix not in tables_result:
        # Unknown format — return as-is so we don't lose info.
        return tables_result
    idx = tables_result.index(prefix) + len(prefix)
    raw_names = [t.strip() for t in tables_result[idx:].split(",") if t.strip()]
    filtered = [t for t in raw_names if t in allowed]
    if not filtered:
        return f"{prefix} (none of the selected files have tables here)"
    return f"{prefix} {', '.join(filtered)}"


@mcp.tool()
async def list_tables() -> str:
    """List all tables across all connected databases.

    When both a primary database and a session file are connected, tables from
    each source are shown separately so the caller can distinguish them.
    """
    if _primary_adapter is None and _session_adapter is None:
        raise RuntimeError(
            "Database not connected. Please use 'connect_db' (PostgreSQL) or "
            "'connect_sqlite' (SQLite) tool first."
        )

    parts: list[str] = []

    if _primary_adapter is not None:
        primary_result = await _primary_adapter.list_tables()
        if _session_adapter is not None:
            parts.append(f"[Primary database]\n{primary_result}")
        else:
            parts.append(primary_result)

    if _session_adapter is not None:
        session_result = await _session_adapter.list_tables()
        # Filter to only the tables the user actually selected (if a restriction is set).
        if _session_allowed_tables:
            session_result = _filter_tables_result(session_result, _session_allowed_tables)
        if _primary_adapter is not None:
            parts.append(f"[Session file database]\n{session_result}")
        else:
            parts.append(session_result)

    return "\n\n".join(parts)


